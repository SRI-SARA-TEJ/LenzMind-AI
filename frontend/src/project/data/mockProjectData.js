// ── Date helper ───────────────────────────────────────────────────────────────
const d = (offsetDays = 0, offsetHours = 0) => {
  const dt = new Date();
  dt.setDate(dt.getDate() - offsetDays);
  dt.setHours(dt.getHours() - offsetHours);
  return dt.toISOString();
};

